export type Key = keyof typeof D;
type Vars = Record<string, string | number>;
const fill = (s: string, v?: Vars) => (v ? s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m)) : s);

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key | (string & {}), v?: Vars) => string;
  errorText: (e: unknown) => string;
  ago: (ms: number) => string;
}

const LangContext = createContext<Ctx | null>(null);

export function LangProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = useCallback((l: Lang) => {
    document.cookie = `bc_lang=${l}; path=/; max-age=31536000; samesite=lax`;
    document.documentElement.lang = l === 'zh' ? 'zh-Hant-HK' : 'en';
    setLangState(l);
  }, []);
  const value = useMemo<Ctx>(() => {
    const i = lang === 'zh' ? 0 : 1;
    const t = (k: string, v?: Vars) => (k in D ? fill(D[k as Key][i], v) : k);
    const locale = lang === 'zh' ? 'zh-HK' : 'en-HK';
    return {
      lang, setLang, t,
      errorText: (e) => {
        if (e instanceof ApiError) {
          if (e.code === 'LOCKED') {
            const n = (e.data as { minutes?: number } | undefined)?.minutes;
            return n ? t('err.LOCKED_N', { n }) : t('err.LOCKED');
          }
          const key = `err.${e.code}`;
          if (e.code && key in D) return t(key);
          if (e.status === 404) return t('err.NOT_FOUND');
          if (e.status >= 500) return t('err.SERVER_ERROR');
        }
        return t('err.uncoded', { msg: e instanceof Error ? e.message : String(e) });
      },
      ago: (ms) => {
        const s = Math.round((Date.now() - ms) / 1000);
        if (s < 60) return t('common.justNow');
        const rtf = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
        if (s < 3600) return rtf.format(-Math.floor(s / 60), 'minute');
        if (s < 86400) return rtf.format(-Math.floor(s / 3600), 'hour');
        if (s < 86400 * 30) return rtf.format(-Math.floor(s / 86400), 'day');
        return new Date(ms).toLocaleDateString(locale);
      },
    };
  }, [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT() {
  const c = useContext(LangContext);
  if (!c) throw new Error('useT outside LangProvider');
  return c;
}
